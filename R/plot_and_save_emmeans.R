#' Plot and Save Estimated Marginal Means (EMMs)
#'
#' This function computes the estimated marginal means (EMMs) from a model object, creates a plot of the EMMs with confidence intervals, and saves the plot to a specified directory. This is particularly useful in studies like mystery caller studies where you need to analyze differences in outcomes such as appointment wait times across different groups or treatments.
#'
#' @param model_object A fitted model object of class `glm`, `lm`, `lmerMod`,
#'   `glmerMod`, or any class supported by [emmeans::emmeans()].
#' @param specs Character scalar or vector. Predictor variable(s) for which
#'   marginal means are computed. The first element is used as the x-axis
#'   variable; the second (if present) becomes the `color_by` grouping
#'   variable. Example: `c("insurance", "gender")`.
#' @param variable_of_interest Character scalar. Label for the x-axis, typically
#'   equal to the first element of `specs`.
#' @param color_by Character scalar or `NULL`. Grouping variable name for
#'   coloring points and error bars. When `NULL` a single-group plot is drawn.
#' @param output_dir A character string specifying the directory where the plot will
#'   be saved. Defaults to a session-specific folder inside [tempdir()].
#'
#' @return `invisible()` named list with two elements: `data` (data.frame of
#'   EMMs from [emmeans::emmeans()]) and `plot` (`ggplot` object). A plot
#'   file is also written to `output_dir` as a side effect.
#'
#' @details The function computes EMMs using the `emmeans` package, which provides adjusted means (or other summary statistics) for the levels of factors, corrected for the influence of other predictors in the model. This is particularly useful in the context of mystery caller studies, where you might want to compare outcomes such as appointment wait times between different insurance types, scenarios, or demographic groups, while controlling for potential confounders.
#'
#' The plot generated by this function displays the EMMs along with their 95% confidence intervals, making it easy to visualize the differences between groups. The plot is saved to a specified directory with a unique filename that includes a timestamp.
#'
#' @examplesIf interactive()
#' # Example 1: Comparing Appointment Wait Times Between Scenarios
#' # Assume 'model' is a fitted GLM object with appointment wait time as the outcome
#' result <- mysterycall_plot_emmeans(
#'   model_object = model,
#'   specs = "scenario",
#'   variable_of_interest = "scenario",
#'   color_by = "insurance",
#'   output_dir = "Figures/ScenarioComparison"
#' )
#'
#' # Example 2: Comparing EMMs Across Different Insurance Types
#' # Assume 'model' is a fitted GLM object
#' result <- mysterycall_plot_emmeans(
#'   model_object = model,
#'   specs = "insurance",
#'   variable_of_interest = "insurance",
#'   color_by = "academic",
#'   output_dir = "Figures/InsuranceComparison"
#' )
#'
#' # Example 3: Visualizing EMMs for Different Age Groups in a Mystery Caller Study
#' # Assume 'model' is a fitted GLM object with age groups as a factor
#' result <- mysterycall_plot_emmeans(
#'   model_object = model,
#'   specs = "age_group",
#'   variable_of_interest = "age_group",
#'   color_by = "gender",
#'   output_dir = "Figures/AgeGroupComparison"
#' )
#'
#' # Example 4: Interaction Effects Between Gender and Insurance Type
#' # Assume 'model' is a fitted GLM object
#' result <- mysterycall_plot_emmeans(
#'   model_object = model,
#'   specs = c("gender", "insurance"),
#'   variable_of_interest = "gender",
#'   color_by = "insurance",
#'   output_dir = "Figures/InteractionEffects"
#' )
#'
#' @family plotting
#' @seealso [mysterycall_plot_emmeans_interaction()] (lean interaction EMM plot)
#'   and [mysterycall_plot_emmeans_full()] (interaction plot with more options
#'   and optional file save). This function computes, plots, and saves a
#'   single-variable EMM figure.
#' @export
mysterycall_plot_emmeans <- function(model_object, specs, variable_of_interest, color_by = NULL, output_dir = NULL) {
  # Load necessary packages
  if (!requireNamespace("emmeans", quietly = TRUE)) {
    stop("Package 'emmeans' is required but not installed.", call. = FALSE)
  }
  if (!requireNamespace("ggplot2", quietly = TRUE)) {
    stop("Package 'ggplot2' is required but not installed.", call. = FALSE)
  }
  if (!requireNamespace("dplyr", quietly = TRUE)) {
    stop("Package 'dplyr' is required but not installed.", call. = FALSE)
  }

  # Explicit input validation
  if (!is.object(model_object) && !is.environment(model_object)) {
    stop("model_object must be a valid model class object", call. = FALSE)
  }
  if (!is.character(specs) || length(specs) == 0) {
    stop("specs must be a single character string", call. = FALSE)
  }
  if (!is.character(variable_of_interest) || length(variable_of_interest) != 1) {
    stop("variable_of_interest must be a single character string", call. = FALSE)
  }
  if (!is.null(output_dir) && !dir.exists(output_dir)) {
    stop("Output directory does not exist: ", output_dir, call. = FALSE)
  }

  # Get the current timestamp for unique file naming
  timestamp <- format(Sys.time(), "%Y%m%d_%H%M%S")

  # Compute estimated marginal means
  message("Computing estimated marginal means...")
  edata <- tryCatch({
    emmeans::emmeans(object = model_object, specs = specs, type = "response") %>%
      as.data.frame()
  }, error = function(e) {
    stop("Error in calculating emmeans: ", e$message, call. = FALSE)
  })

  # Log the retrieved data
  message("Estimated data:")
  invisible(edata)

  # Detect response and CI column names - names differ by model family:
  # Poisson/response scale: "rate", "asymp.LCL", "asymp.UCL"
  # Gaussian / emmean scale: "emmean", "lower.CL", "upper.CL"
  response_col <- intersect(c("rate", "emmean", "response", "prob"), names(edata))
  lcl_col      <- intersect(c("asymp.LCL", "lower.CL", "lower.HPD"), names(edata))
  ucl_col      <- intersect(c("asymp.UCL", "upper.CL", "upper.HPD"), names(edata))

  if (!length(response_col) || !length(lcl_col) || !length(ucl_col)) {
    stop(sprintf(
      "Could not identify emmeans response/CI columns. Available columns: %s",
      paste(names(edata), collapse = ", ")
    ), call. = FALSE)
  }
  response_col <- response_col[[1]]
  lcl_col      <- lcl_col[[1]]
  ucl_col      <- ucl_col[[1]]

  # Check the range of the estimated data
  rate_range <- range(c(edata[[lcl_col]], edata[[ucl_col]]), na.rm = TRUE)
  if (any(is.infinite(rate_range))) {
    stop("CI columns contain no finite values; cannot set y-axis limits.", call. = FALSE)
  }
  message("Range of estimated marginal means with CIs: ", rate_range)

  # Create the plot
  message("Creating the plot...")
  if (!is.null(color_by)) {
    point_aes  <- ggplot2::aes(color = .data[[color_by]])
    bar_aes    <- ggplot2::aes(ymin = .data[[lcl_col]], ymax = .data[[ucl_col]], color = .data[[color_by]])
  } else {
    point_aes  <- ggplot2::aes()
    bar_aes    <- ggplot2::aes(ymin = .data[[lcl_col]], ymax = .data[[ucl_col]])
  }
  p <- ggplot2::ggplot(edata, ggplot2::aes(x = .data[[variable_of_interest]], y = .data[[response_col]])) +
    ggplot2::geom_point(point_aes, size = 2, stroke = 2,
                        position = ggplot2::position_dodge(width = 0.2)) +
    ggplot2::geom_errorbar(bar_aes,
                           width = 0.2, position = ggplot2::position_dodge(width = 0.2)) +
    ggplot2::ylim(rate_range[1] - 5, rate_range[2] + 5) +
    ggplot2::ggtitle(paste("Estimated Marginal Means -", variable_of_interest)) +
    ggplot2::ylab("Estimated Marginal Means for Waiting Time in Days\nMean +/-  95% CI") +
    ggplot2::theme_minimal() +
    ggplot2::theme(axis.text.x = ggplot2::element_text(angle = 45, hjust = 1, vjust = 1, size = 10, color = "black"),
                   legend.position = "bottom") +
    ggplot2::scale_x_discrete(labels = function(x) gsub(" ", "\n", x))

  # Ensure the output directory exists
  if (is.null(output_dir)) {
    output_dir <- mysterycall_tempdir("emmeans_plots", create = TRUE)
  } else if (!dir.exists(output_dir)) {
    dir.create(output_dir, recursive = TRUE, showWarnings = FALSE)
  }

  # Save the plot with specific dimensions
  file_name <- file.path(output_dir, paste0("interaction_", variable_of_interest, "_comparison_plot_", timestamp, ".png"))
  message("Saving plot to: ", file_name)
  ggplot2::ggsave(filename = file_name, plot = p, width = 10, height = 6, bg = "white")

  message("Plot saved successfully.")

  # Return the data and plot invisibly
  invisible(list(data = edata, plot = p))
}
